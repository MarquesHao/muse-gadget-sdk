"""Generate the embedded boot/fallback still source for muse_frames.c.

Usage: gen_boot_still.py INPUT.jpg OUTPUT.c

Reads a 466x466 JPEG (the frame library's waking first frame is the
natural source: the still then continues into the waking sequence
with no visible step) and writes a C file defining muse_boot_still_jpg()
over the embedded bytes. The output belongs in the gitignored
components/muse/avatar/ directory: the artwork it embeds is the
board owner's own and is not part of the repository. CMake prefers
avatar/muse_boot_still.c over the committed stub; see
components/muse/muse_boot_still.h.
"""

import struct
import sys

WANT_W = 466
WANT_H = 466


def jpeg_size(data):
    """(width, height) from the first SOF segment, or None."""
    if len(data) < 4 or data[0] != 0xFF or data[1] != 0xD8:
        return None
    pos = 2
    while pos + 1 < len(data):
        if data[pos] != 0xFF:
            return None
        marker = data[pos + 1]
        pos += 2
        if marker in (0xD8, 0xD9, 0x01) or 0xD0 <= marker <= 0xD7:
            continue  # standalone markers carry no length
        if pos + 2 > len(data):
            return None
        (seg_len,) = struct.unpack(">H", data[pos:pos + 2])
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            if pos + 7 > len(data):
                return None
            height, width = struct.unpack(">HH", data[pos + 3:pos + 7])
            return width, height
        if marker == 0xDA:  # SOS: the SOF must have come by now
            return None
        pos += seg_len
    return None


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    src_path, out_path = argv[1], argv[2]
    with open(src_path, "rb") as f:
        data = f.read()
    size = jpeg_size(data)
    if size is None:
        print(f"{src_path}: not a readable JPEG", file=sys.stderr)
        return 1
    if size != (WANT_W, WANT_H):
        print(f"{src_path}: {size[0]}x{size[1]}, want {WANT_W}x{WANT_H}",
              file=sys.stderr)
        return 1
    lines = [
        "/* Generated by tools/gen_boot_still.py — do not edit by hand.",
        " *",
        " * The artwork embedded below is the board owner's own and is",
        " * NOT part of the repository: this file lives in the gitignored",
        " * components/muse/avatar/ area (see muse_boot_still.h).",
        f" * Source image: {WANT_W}x{WANT_H} JPEG, {len(data)} bytes. */",
        "",
        '#include "muse_boot_still.h"',
        "",
        "static const uint8_t s_boot_still_jpg[] __attribute__((aligned(4))) = {",
    ]
    for off in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[off:off + 16])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        "const uint8_t *muse_boot_still_jpg(size_t *len_out)",
        "{",
        "    if (len_out) {",
        "        *len_out = sizeof(s_boot_still_jpg);",
        "    }",
        "    return s_boot_still_jpg;",
        "}",
        "",
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"{out_path}: embedded {len(data)} bytes ({WANT_W}x{WANT_H})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
